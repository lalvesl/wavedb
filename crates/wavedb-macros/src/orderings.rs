//! The `by_<fields>` lookups of every declared ordering ([RFC 0075]): a
//! `#[wavedb::pivot(...)]` secondary and a `#[wavedb::list]` are one chain
//! that differs only in its payload, so both answer the same two lookups —
//! the exact value(s) and a half-open range over the `IndexKey` encoding.
//!
//! A pivot's lookups resolve two-phase (anchors, then a fetch each); a list's
//! read the records inline. Declaring both on one ordering is refused: the
//! list already answers everything the pivot would, and faster, so the pivot
//! would only cost writes.
//!
//! [RFC 0075]: ../../../rfcs/0075-secondary-indexes-as-chains.md

use proc_macro2::{Span, TokenStream};
use quote::{format_ident, quote};
use syn::{Ident, Type};

use crate::lists::ResolvedList;
use crate::secondaries::ResolvedPivot;

/// Which chain an ordering's lookups read, and at which declaration index.
#[derive(Clone, Copy)]
enum Source {
    Pivot(usize),
    List(usize),
}

/// Refuse a `#[wavedb::pivot]` and a `#[wavedb::list]` over the same
/// ordering.
///
/// # Errors
/// The compile error naming the ordering.
pub fn check(
    pivots: &[ResolvedPivot],
    lists: &[ResolvedList],
) -> syn::Result<()> {
    for pivot in pivots {
        if lists.iter().any(|l| same_fields(&l.order, pivot)) {
            return Err(syn::Error::new(
                Span::call_site(),
                format!(
                    "`{}` is declared both #[wavedb::pivot] and #[wavedb::list]: \
                     the list already answers `by_{}` with the records inline, \
                     so the pivot would only cost writes — keep one",
                    pivot.joined(),
                    pivot.joined(),
                ),
            ));
        }
    }
    Ok(())
}

fn same_fields(a: &ResolvedPivot, b: &ResolvedPivot) -> bool {
    a.fields.len() == b.fields.len()
        && a.fields
            .iter()
            .zip(&b.fields)
            .all(|((x, _), (y, _))| x == y)
}

/// The borrowed parameter type a lookup takes for a field: `&str` for a
/// `String` field (the `IndexKey` encodings agree), `&T` otherwise.
fn param_ty(ty: &Type) -> TokenStream {
    if let Type::Path(p) = ty
        && p.path
            .segments
            .last()
            .is_some_and(|seg| seg.ident == "String")
    {
        return quote!(&str);
    }
    quote!(&#ty)
}

/// The `{Name}Secondaries` trait + its `CollectionHandle<{Name}>` impl: per
/// declared ordering, pivot or list, `by_<fields>` (exact) and
/// `by_<fields>_range` (half-open).
pub fn lookups(
    name: &Ident,
    pivots: &[ResolvedPivot],
    lists: &[ResolvedList],
) -> TokenStream {
    let orderings: Vec<(&ResolvedPivot, Source)> = pivots
        .iter()
        .enumerate()
        .map(|(i, p)| (p, Source::Pivot(i)))
        .chain(
            lists
                .iter()
                .enumerate()
                .map(|(i, l)| (&l.order, Source::List(i))),
        )
        .collect();
    if orderings.is_empty() {
        return TokenStream::new();
    }
    let trait_ident = format_ident!("{}Secondaries", name);
    let decls = orderings.iter().map(|(o, _)| lookup_items(name, o, None));
    let impls = orderings
        .iter()
        .map(|(o, source)| lookup_items(name, o, Some(*source)));
    quote! {
        /// Typed lookups for this type's collection, one pair per
        /// `#[wavedb::pivot(...)]` and per `#[wavedb::list]` (generated by
        /// `#[wavedb]`).
        pub trait #trait_ident {
            #(#decls)*
        }

        impl #trait_ident for ::wavedb_core::CollectionHandle<#name> {
            #(#impls)*
        }
    }
}

/// One ordering's two lookups, as declarations (`source = None`) or as the
/// implementations reading `source`.
fn lookup_items(
    name: &Ident,
    order: &ResolvedPivot,
    source: Option<Source>,
) -> TokenStream {
    let by = format_ident!("by_{}", order.joined());
    let range = format_ident!("by_{}_range", order.joined());
    let names: Vec<&Ident> = order.fields.iter().map(|(f, _)| f).collect();
    let tys: Vec<TokenStream> =
        order.fields.iter().map(|(_, t)| param_ty(t)).collect();
    let (bound_ty, key_of) = if names.len() == 1 {
        (tys[0].clone(), quote!(::wavedb_core::IndexKey::key_bytes))
    } else {
        (
            quote!((#(#tys),*)),
            quote!(|v| ::wavedb_core::IndexKey::key_bytes(&v)),
        )
    };
    let exact_key = if names.len() == 1 {
        let f = names[0];
        quote!(::wavedb_core::IndexKey::key_bytes(#f))
    } else {
        quote!(::wavedb_core::IndexKey::key_bytes(&(#(#names),*)))
    };
    let params = names.iter().zip(&tys).map(|(f, t)| quote!(#f: #t));
    let stream = quote! {
        impl ::wavedb_core::Stream<
            Item = ::core::result::Result<#name, D::Error>,
        >
    };
    let Some(source) = source else {
        return quote! {
            /// Stream the living records whose ordering value(s) equal the
            /// given one(s), in its order.
            fn #by<D: ::wavedb_core::DbHandle>(
                &self,
                db: &D,
                #(#params),*
            ) -> #stream;

            /// Stream the living records whose ordering value lies in
            /// `[lo, hi)`, in its order.
            fn #range<D: ::wavedb_core::DbHandle>(
                &self,
                db: &D,
                lo: #bound_ty,
                hi: #bound_ty,
            ) -> #stream;
        };
    };
    let read = |bound: TokenStream| match source {
        Source::Pivot(i) => quote!(self.search_by(db, #i, #bound)),
        Source::List(i) => quote!(self.listed_where(db, #i, #bound)),
    };
    let exact = read(quote!(::wavedb_core::Bound::Exact(#exact_key)));
    let ranged = read(quote!({
        let key = #key_of;
        ::wavedb_core::Bound::Range { lo: key(lo), hi: key(hi) }
    }));
    quote! {
        fn #by<D: ::wavedb_core::DbHandle>(
            &self,
            db: &D,
            #(#params),*
        ) -> #stream {
            #exact
        }

        fn #range<D: ::wavedb_core::DbHandle>(
            &self,
            db: &D,
            lo: #bound_ty,
            hi: #bound_ty,
        ) -> #stream {
            #ranged
        }
    }
}
